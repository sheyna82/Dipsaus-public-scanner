"""Offline, pre-decision RS/ATR annotations for frozen historical events.

This module does NOT tune thresholds or claim predictive performance.
RS uses the same 20-session history as SPY; ATR is based on 14 completed
stock bars. Events remain generated by the original frozen rule.
"""
from math import isfinite
from dipsaus_offline_ohlcv_features import _valid
from dipsaus_offline_event_history_outcomes import evaluate_daily_event_history


def annotate_frozen_events_rs_atr(stock, benchmark, *, horizon=10):
    if (not _valid(stock) or not _valid(benchmark)
            or len(stock) != len(benchmark)
            or [x["date"] for x in stock] != [x["date"] for x in benchmark]
            or type(horizon) is not int or not 2 <= horizon <= 30):
        return {"status": "DATA_BLOCKED", "reason": "invalid_or_unaligned_history", "trade_ready": False}
    events = evaluate_daily_event_history(stock, horizon=horizon)
    if events.get("status") != "DESCRIPTIVE_HISTORY":
        return {"status": "DATA_BLOCKED", "reason": "event_history_blocked", "trade_ready": False}
    by_date = {x["date"]: i for i, x in enumerate(stock)}
    rows = []
    for event in events["outcomes"]:
        i = by_date[event["signal_date"]]
        if i < 21:
            return {"status": "DATA_BLOCKED", "reason": "insufficient_feature_history", "trade_ready": False}
        rs = 100 * ((stock[i]["close"] / stock[i - 20]["close"] - 1)
                    - (benchmark[i]["close"] / benchmark[i - 20]["close"] - 1))
        ranges = []
        for j in range(i - 13, i + 1):
            previous = stock[j - 1]["close"]
            ranges.append(max(stock[j]["high"] - stock[j]["low"],
                              abs(stock[j]["high"] - previous),
                              abs(stock[j]["low"] - previous)))
        atr = 100 * (sum(ranges) / 14) / stock[i]["close"]
        if not isfinite(rs) or not isfinite(atr) or atr <= 0:
            return {"status": "DATA_BLOCKED", "reason": "invalid_feature", "trade_ready": False}
        rows.append({"signal_date": event["signal_date"],
                     "relative_strength_20d_pct_points": round(rs, 6),
                     "atr_14d_pct": round(atr, 6),
                     "terminal_return_net_pct": event["terminal_return_net_pct"],
                     "max_adverse_excursion_pct": event["max_adverse_excursion_pct"]})
    return {"status": "EXPLORATORY_FROZEN_RS_ATR", "events": len(rows), "rows": rows,
            "thresholds_selected": False, "independent_holdout": False,
            "source_verified": False, "predictive_edge_proven": False, "trade_ready": False}
