"""Regression against recorded real exchange_calendars 4.13.1 output.

Recorded in a local environment on 2026-10-23, not generated by CI.
The dates are reference examples, not independently exchange-verified.
"""
import hashlib
import json
import unittest
from research_exchange_calendar_adapter import audit_calendar_export


def fixture(exchange, sessions):
    canonical = json.dumps(sessions, separators=(",", ":"), ensure_ascii=True)
    return {"exchange": exchange, "calendar_library": "exchange_calendars",
            "calendar_version": "4.13.1",
            "session_dates": sessions,
            "source_sha256": hashlib.sha256(canonical.encode("ascii")).hexdigest(),
            "digest_scope": "canonical_session_dates_json"}


class RealCalendarRecordedTests(unittest.TestCase):
    def test_xnys_mlk_holiday_recorded_sessions(self):
        dates = ["2025-01-16", "2025-01-17", "2025-01-21",
                 "2025-01-22", "2025-01-23"]
        report = audit_calendar_export(dates, fixture("XNYS", dates))
        self.assertTrue(report["complete_against_supplied_calendar"])
        self.assertTrue(report["calendar_export_digest_verified"])
        self.assertFalse(report["calendar_provenance_verified"])
        incomplete = audit_calendar_export(
            [dates[0], dates[1], dates[3], dates[4]], fixture("XNYS", dates))
        self.assertEqual(incomplete["missing_expected_sessions"], ["2025-01-21"])

    def test_xams_easter_recorded_sessions(self):
        dates = ["2025-04-16", "2025-04-17", "2025-04-22", "2025-04-23"]
        report = audit_calendar_export(dates, fixture("XAMS", dates))
        self.assertTrue(report["complete_against_supplied_calendar"])
        self.assertFalse(report["calendar_provenance_verified"])
        unexpected = audit_calendar_export(
            ["2025-04-16", "2025-04-17", "2025-04-18", "2025-04-22", "2025-04-23"],
            fixture("XAMS", dates))
        self.assertEqual(unexpected["unexpected_price_dates"], ["2025-04-18"])


if __name__ == "__main__":
    unittest.main()
